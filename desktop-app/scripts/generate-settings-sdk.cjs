const fs = require('node:fs'),
  path = require('node:path'),
  vm = require('node:vm'),
  ts = require('typescript');
const root = path.resolve(__dirname, '..');
const write = (file, content) => {
  const target = path.join(root, file);
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content)
    fs.writeFileSync(target, content);
};
const moduleValue = { exports: {} };
vm.runInNewContext(
  ts.transpileModule(
    fs.readFileSync(path.join(root, 'src/main/theme-settings-request-documentation.ts'), 'utf8'),
    { compilerOptions: { module: ts.ModuleKind.CommonJS } },
  ).outputText,
  { exports: moduleValue.exports },
);
write(
  'src/interactive/settings-contract.d.ts',
  '// Generated contract mirror; checked against the handbook by tests.\n' +
    moduleValue.exports.SETTINGS_REQUEST_DECLARATIONS,
);
const entry = path.join(root, 'src/interactive/settings-sdk.ts');
const chatEntry = path.join(root, 'src/interactive/chat-sdk.ts');
const effectsEntry = path.join(root, 'src/interactive/effects-sdk.ts');
const storageEntry = path.join(root, 'src/interactive/theme-storage-sdk.ts');
const program = ts.createProgram([entry, chatEntry, effectsEntry, storageEntry], {
  target: ts.ScriptTarget.ES2020,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  esModuleInterop: true,
  strict: true,
  skipLibCheck: true,
  declaration: true,
  emitDeclarationOnly: true,
  types: [],
  jsx: ts.JsxEmit.ReactJSX,
});
const errors = ts
  .getPreEmitDiagnostics(program)
  .filter((item) => item.category === ts.DiagnosticCategory.Error);
if (errors.length) {
  console.error(
    ts.formatDiagnosticsWithColorAndContext(errors, {
      getCanonicalFileName: (f) => f,
      getCurrentDirectory: () => root,
      getNewLine: () => '\n',
    }),
  );
  process.exit(1);
}
const declarations = {};
program.emit(undefined, (file, content) => {
  const name = path.basename(file);
  if (
    ['settings-sdk.d.ts', 'settings-store.d.ts', 'chat-sdk.d.ts', 'chat-store.d.ts', 'effects-sdk.d.ts','theme-effects-types.d.ts','theme-storage-sdk.d.ts','theme-storage-types.d.ts'].includes(name)
  )
    declarations[name] = content;
});
const sdk = declarations['settings-sdk.d.ts']
  .replaceAll('./settings-contract', './chatter')
  .replace(
    "import type { ThemeSettingField, ThemeSettingsState } from '../main/settings-shell-types';",
    "import type { SettingsField as ThemeSettingField, SettingsState as ThemeSettingsState } from './chatter';",
  );
write('src/main/theme-effects-sdk-declarations.ts',
  '// Generated by scripts/generate-settings-sdk.cjs.\nexport const EFFECTS_SDK_TYPES=' +
  JSON.stringify(declarations['effects-sdk.d.ts'].replaceAll('../main/theme-effects-types','./theme-effects-types')) +
  ';\nexport const EFFECTS_CONTRACT_TYPES=' + JSON.stringify(declarations['theme-effects-types.d.ts']) + ';\n');
write('src/main/theme-storage-sdk-declarations.ts',
  '// Generated by scripts/generate-settings-sdk.cjs.\nexport const STORAGE_SDK_TYPES=' +
  JSON.stringify(declarations['theme-storage-sdk.d.ts'].replaceAll('../main/theme-storage-types','./theme-storage-types')) +
  ';\nexport const STORAGE_CONTRACT_TYPES=' + JSON.stringify(declarations['theme-storage-types.d.ts']) + ';\n');
const source = program.getSourceFile(entry);
const hooks = source.statements
  .filter(
    (node) =>
      ts.isFunctionDeclaration(node) &&
      node.name?.text.startsWith('use') &&
      node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword),
  )
  .map((node) => node.name.text);
let ui = hooks
  .map((name) => '  export const ' + name + ":typeof import('./settings-sdk')." + name + ';')
  .join('\n');
for (const node of source.statements)
  if (
    ts.isTypeAliasDeclaration(node) &&
    node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
  ) {
    const parameters = node.typeParameters
      ?.map((p) =>
        p
          .getText(source)
          .replaceAll('SettingsRequestContract', "import('./chatter').SettingsRequestContract"),
      )
      .join(',');
    const args = node.typeParameters?.map((p) => p.name.text).join(',');
    ui +=
      '\n  export type ' +
      node.name.text +
      (parameters ? '<' + parameters + '>' : '') +
      "=import('./settings-sdk')." +
      node.name.text +
      (args ? '<' + args + '>' : '') +
      ';';
  }
ui += "\n  export type SettingsResult<T=void>=import('./settings-sdk').SettingsResult<T>;";
write(
  'src/main/theme-settings-sdk-declarations.ts',
  '// Generated by scripts/generate-settings-sdk.cjs; implementation is the source of public SDK types.\nexport const SETTINGS_SDK_TYPES=' +
    JSON.stringify(sdk) +
    ';\nexport const SETTINGS_STORE_TYPES=' +
    JSON.stringify(declarations['settings-store.d.ts']) +
    ';\nexport const SETTINGS_SDK_UI_EXPORTS=' +
    JSON.stringify(ui) +
    ';\n',
);

const chatTypes = (text) =>
  text
    .replaceAll('../main/appearance-shell-types', './chatter')
    .replace(/\bAppearanceShellState\b/g, 'ThemeState')
    .replace(/\bAppearanceMessageContent\b/g, 'MessageContent')
    .replace(/\bAppearanceContextSummary\b/g, 'ContextSummary')
    .replace(/\bAppearanceMessageInfo\b/g, 'MessageInfo')
    .replace(/\bAppearanceTokenUsage\b/g, 'TokenUsage')
    .replace(/\bAppearanceModels\b/g, 'Models')
    .replace(/\bAppearanceVoice\b/g, 'Voice')
    .replace(/\bAppearanceContext\b/g, 'Context')
    .replace(/\bAppearanceConfirmationNode\b/g, 'ConfirmationNode')
    .replace(/\bAppearanceConfirmationField\b/g, 'ConfirmationField')
    .replace(/\bAppearanceConfirmationAction\b/g, 'ConfirmationAction')
    .replace(/\bAppearanceConfirmation\b/g, 'Confirmation')
    .replace(/\bAppearanceMenuItem\b/g, 'MenuItem')
    .replace(/\bAppearanceChatMenuActionName\b/g, 'ChatMenuAction')
    .replace(/\bAppearanceFolderMenuActionName\b/g, 'FolderMenuAction')
    .replace(/\bAppearanceMessageActionName\b/g, 'MessageAction')
    .replace(/\bAppearanceWorkLogStep\b/g, 'WorkLogStep')
    .replace(/\bAppearanceToolCall\b/g, 'ToolCall')
    .replace(/\bAppearanceLabelKey\b/g, 'LabelKey')
    .replace(/\bAppearanceLabels\b/g, 'Labels')
    .replace(/\bAppearanceReasoningLevel\b/g, 'ReasoningLevel');
const chatSource = program.getSourceFile(chatEntry);
let chatUi = '';
for (const node of chatSource.statements) {
  if (!node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) continue;
  if (ts.isFunctionDeclaration(node))
    chatUi +=
      '  export const ' + node.name.text + ":typeof import('./chat-sdk')." + node.name.text + ';\n';
  if (ts.isTypeAliasDeclaration(node)) {
    const params = node.typeParameters?.map((p) => p.getText(chatSource)).join(',');
    const args = node.typeParameters?.map((p) => p.name.text).join(',');
    chatUi +=
      '  export type ' +
      node.name.text +
      (params ? '<' + params + '>' : '') +
      "=import('./chat-sdk')." +
      node.name.text +
      (args ? '<' + args + '>' : '') +
      ';\n';
  }
}
write(
  'src/main/theme-chat-sdk-declarations.ts',
  '// Generated by scripts/generate-settings-sdk.cjs; implementation is the source of public SDK types.\n' +
    'export const CHAT_SDK_TYPES=' +
    JSON.stringify(chatTypes(declarations['chat-sdk.d.ts'])) +
    ';\n' +
    'export const CHAT_STORE_TYPES=' +
    JSON.stringify(chatTypes(declarations['chat-store.d.ts'])) +
    ';\n' +
    'export const CHAT_SDK_UI_EXPORTS=' +
    JSON.stringify(chatUi) +
    ';\n',
);
